const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const data = read('utils/portrait-report-data.uts')
const report = read('pagesSub/profileExtra/components/moxiang/MoxiangReportSheet.uvue')
const metrics = read('pagesSub/profileExtra/components/moxiang/MoxiangMetricsSheet.uvue')
const archive = read('pagesSub/profileExtra/my-portrait-archive.uvue')
assert.match(data, /narrative\.status == 'confirmed' \|\| narrative\.status == 'published'/)
assert.match(data, /narrative\.subject == subject/)
assert.match(data, /Number\(narrative\.revision_id\) == revision\.revisionId/)
assert.match(data, /revisionId != revision\.revisionId/)
assert.match(data, /field\.field_kind == 'entry'/)
assert.match(data, /field\.field_kind == 'structured'/)
assert.doesNotMatch(data, /emotional_insight/)
assert.match(data, /percent: point != null \? point\.percent : null/)
assert.match(data, /history\.subject != report\.subject/)
assert.match(archive, /<MoxiangReportSheet v-if="reportSheetVisible && archivePageVisible"/)
assert.match(report, /伴侣期待仅本人可见，不支持导出/)
assert.match(metrics, /series\.length < 2/)
assert.match(metrics, /percentText\(dim\.percent\)/)
assert.doesNotMatch(report + metrics, /竞争力|脱单难度|最后机会|成功率|会员专属/)
assert.match(archive, /openReport\('report'\)/)
assert.match(archive, /openReport\('metrics'\)/)
console.log('PASS portrait report source contract: confirmed-only, subject/revision isolation, nulls, entry points')
