assert(firstAnalysis.includes('class="analysis-card"'), '首次分析视图应保持原 AI 卡片尺寸')
assert(!firstAnalysis.includes('position: fixed'), '首次分析视图不能覆盖为全屏浮层')
assert(card.includes('ai-empty-main'), '资料页空态应使用方案 A 的双栏引导')
assert(!card.includes('class="ai-stale"'), '结果卡不应再显示绿色资料更新提示块')
assert(card.includes('分析最新资料'), '结果卡底部必须显示分析最新资料按钮')
assert(!card.includes('class="ai-score"'), '结果态顶部不应重复显示分数')
